class I18nManager:
    """다국어 번역 상태 관리 싱글톤 클래스"""
    _instance = None

    def __new__(cls):
        if cls._instance is None:
            cls._instance = super(I18nManager, cls).__new__(cls)
            cls._instance._settings = QSettings("CompanionTurret", "CT_Dashcam_Studio")
            cls._instance._current_lang = cls._instance._settings.value("app_language", "ko")
            if cls._instance._current_lang not in LANGUAGES:
                cls._instance._current_lang = "ko"
        return cls._instance

    @property
    def current_language(self):
        return self._current_lang

    @current_language.setter
    def current_language(self, lang_code):
        if lang_code in LANGUAGES:
            self._current_lang = lang_code
            self._settings.setValue("app_language", lang_code)

    def tr(self, key, **kwargs):
        lang_dict = TRANSLATIONS.get(self._current_lang, TRANSLATIONS["ko"])
        text = lang_dict.get(key)
        if text is None:
            text = TRANSLATIONS["ko"].get(key, key)
        if kwargs:
            try:
                return text.format(**kwargs)
            except Exception:
                return text
        return text


